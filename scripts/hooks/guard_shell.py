#!/usr/bin/env python
"""PreToolUse hook on the shell tool: block commands that would break the competition's data and
history rules. Exit 2 blocks the call and the reason (stderr) goes back to the agent; exit 0 allows.

Blocked:
  * `git add` of anything under data/ (synthetic volumes, weights, rules PDF, DB) or of model /
    volume files (*.pt, *.pth, *.safetensors, *.npy, *.sgy, *.segy, *.vds, *.zarr) - public repo,
    weights are under Meta's licence and volumes are regenerated by scripts/;
  * `git add -f` / `--force` (would bypass .gitignore);
  * force pushes and `git reset --hard` (no destructive history changes without the owner).
A command can be given as an argument for manual testing."""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _event import read_event, strings_under  # noqa: E402

RULES = (
    (re.compile(r"\bgit\s+add\b[^;&|\n]*?(?:^|\s|[\"'])\.?[/\\]?data[/\\]", re.I),
     "git add of a path under data/ (generated volumes, weights, rules PDF and the DB are never committed; "
     "regenerate data with scripts/generate_synthetic_seismic.py)"),
    (re.compile(r"\bgit\s+add\b[^;&|\n]*\.(?:pt|pth|safetensors|npy|sgy|segy|vds|zarr)\b", re.I),
     "git add of a model or volume file (weights stay under Meta's SAM License outside git; volumes are generated)"),
    (re.compile(r"\bgit\s+add\b[^;&|\n]*\s(?:-f|--force)\b", re.I),
     "git add --force would bypass .gitignore"),
    (re.compile(r"\bgit\s+push\b[^;&|\n]*\s(?:-f|--force|--force-with-lease)\b|\bgit\s+push\b[^;&|\n]*\s\+\S", re.I),
     "force push (the branch history is shared; push fast-forward only)"),
    (re.compile(r"\bgit\s+reset\b[^;&|\n]*--hard\b", re.I),
     "git reset --hard discards work; ask the owner first"),
)


def main() -> int:
    cmds = sys.argv[1:] or strings_under(read_event(), ("command", "cmd", "script"))
    for cmd in cmds:
        for rx, why in RULES:
            if rx.search(cmd):
                print(f"Blocked by .kiro/hooks/dev-loop.json: {why}.\nCommand: {cmd}", file=sys.stderr)
                return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
